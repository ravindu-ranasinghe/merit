// Regenerates src/lib/chain/escrow-abi.ts from Engineer A's published ABI.
// Run `npm run sync-abi` whenever docs/escrow-abi.json changes.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const src = fileURLToPath(new URL("../../docs/escrow-abi.json", import.meta.url));
const out = fileURLToPath(new URL("../src/lib/chain/escrow-abi.ts", import.meta.url));

const parsed = JSON.parse(readFileSync(src, "utf8"));
const abi = Array.isArray(parsed) ? parsed : parsed.abi;
if (!Array.isArray(abi)) throw new Error("docs/escrow-abi.json has no ABI array");

writeFileSync(
  out,
  `// GENERATED by scripts/sync-abi.mjs from docs/escrow-abi.json. Do not edit by hand.
export const escrowAbi = ${JSON.stringify(abi, null, 2)} as const;
`,
);
console.log(`Wrote ${abi.length} ABI entries to src/lib/chain/escrow-abi.ts`);
